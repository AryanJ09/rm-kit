// Create one minimal Storybook story per rm-style/ui component so the Controls panel has something to edit.
// Run from apps/v4:  node scripts/generate-ui-stories.mjs [name ...]   (name = file basename, e.g. button)
// Existing *.stories.tsx files are skipped. Files with no PascalCase export are listed at the end.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const UI = path.join(ROOT, "rm-style/ui")

// Main component = first PascalCase name in an `export { ... }` block that is not a type export.
// `export type ...` and `type X` inside braces are skipped; `A as B` uses B.
function mainComponent(src) {
  for (const [, body] of src.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const raw of body.split(",")) {
      const item = raw.trim()
      if (!item || item.startsWith("type ")) continue
      const name = item.split(/\s+as\s+/).pop().trim()
      if (/^[A-Z]/.test(name)) return name
    }
  }
  return null
}

function storyFor(name, component) {
  // No `: Story` annotation on Default: components with required props would fail the type check on `{}`.
  return `// Generated by scripts/generate-ui-stories.mjs. Edit freely; the generator skips existing files.
import type { Meta } from "@storybook/nextjs-vite"
import { ${component} } from "./${name}"

const meta = {
  component: ${component},
} satisfies Meta<typeof ${component}>

export default meta

export const Default = {}
`
}

const only = process.argv.slice(2)
const files = fs.readdirSync(UI).filter((f) => f.endsWith(".tsx") && !f.endsWith(".stories.tsx"))
const created = []
const skipped = []
const noComponent = []

for (const file of files) {
  const name = file.replace(/\.tsx$/, "")
  if (only.length && !only.includes(name)) continue
  const storyPath = path.join(UI, `${name}.stories.tsx`)
  if (fs.existsSync(storyPath)) { skipped.push(name); continue }
  const component = mainComponent(fs.readFileSync(path.join(UI, file), "utf8"))
  if (!component) { noComponent.push(name); continue }
  fs.writeFileSync(storyPath, storyFor(name, component))
  created.push(`${name} -> ${component}`)
}

console.log(`Created ${created.length}:`)
for (const line of created) console.log(`  ${line}`)
if (skipped.length) console.log(`Skipped (story exists) ${skipped.length}: ${skipped.join(", ")}`)
if (noComponent.length) console.log(`No component export found ${noComponent.length}: ${noComponent.join(", ")}`)
